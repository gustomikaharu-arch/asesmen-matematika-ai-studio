export function getTPDescription(tpId: number, code: 'BB' | 'MB' | 'BSH' | 'SB'): string {
  const tp = TP_LIST.find((t) => t.id === tpId);
  const phrase = tp ? tp.competencyPhrase : 'kompetensi terkait';

  switch (code) {
    case 'SB':
      return `Mampu ${phrase} secara mandiri dan konsisten.`;
    case 'BSH':
      return `Mampu ${phrase} dengan baik, namun masih perlu penguatan pada beberapa bagian.`;
    case 'MB':
      return `Mulai mampu ${phrase}, namun masih memerlukan bimbingan dan latihan.`;
    case 'BB':
      return `Belum mampu ${phrase} secara optimal dan memerlukan bimbingan lebih lanjut.`;
  }
}
